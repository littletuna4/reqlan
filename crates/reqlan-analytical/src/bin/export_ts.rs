use reqlan_analytical::{rewrite_generated_ts_comment_paths, type_collection};

fn main() {
    let types = type_collection();
    let typescript = specta_typescript::Typescript::default()
        .header("// Generated by reqlan-analytical export-ts. Do not edit.\n// rq:[\"../../../reqlan rq/core_analysis/rust_port.rq\".ts_interface]\n");
    match typescript.export(&types) {
        Ok(source) => {
            let source = rewrite_generated_ts_comment_paths(&source);
            let out = std::env::args().nth(1).unwrap_or_else(|| {
                format!(
                    "{}/packages/analytical/src/native/generated.ts",
                    env!("CARGO_MANIFEST_DIR").trim_end_matches("/crates/reqlan-analytical")
                )
            });
            if let Some(parent) = std::path::Path::new(&out).parent() {
                let _ = std::fs::create_dir_all(parent);
            }
            std::fs::write(&out, source).expect("write generated.ts");
            eprintln!("wrote {out}");
        }
        Err(error) => {
            eprintln!("specta export failed: {error}");
            std::process::exit(1);
        }
    }
}
