#!/usr/bin/env node
/**
 * Generates src/graph/physics-core-source.ts from src/graph/physics-core.js.
 *
 * physics-core.js is plain ESM designed to be embedded as a classic script in
 * the HTML export by stripping `export` keywords. Doing that strip at runtime
 * via readFileSync(import.meta.url) is not bundler-safe: esbuild with format cjs
 * + target es2017 empties import.meta.url, and the file does not exist on disk
 * relative to the bundled main.cjs anyway.
 *
 * This script pre-strips the exports and writes the result as a typed string
 * constant so classic-script embeds can import it directly. Run before tsc.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = join(packageRoot, 'src', 'graph', 'physics-core.js');
const outputPath = join(packageRoot, 'src', 'graph', 'physics-core-source.ts');

const raw = readFileSync(sourcePath, 'utf8');
const classic = raw.replace(/^export\s+/gm, '');

const output = `\
// This file is generated by scripts/generate-physics-core-source.mjs.
// Do not edit manually — update src/graph/physics-core.js and re-run the script.

/**
 * physics-core.js with \`export\` keywords stripped so it can be embedded as a
 * classic (non-module) \`<script>\` tag in the standalone HTML graph export.
 */
export const PHYSICS_CORE_CLASSIC_SOURCE: string = ${JSON.stringify(classic)};
`;

writeFileSync(outputPath, output, 'utf8');
console.log('[analytical] Generated src/graph/physics-core-source.ts');
